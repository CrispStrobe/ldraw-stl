let lang = 'en';
try { lang = localStorage.getItem('ldraw-stl.lang') || ''; } catch { /* storage blocked */ }
if (!STRINGS[lang]) lang = (navigator.language || 'en').toLowerCase().startsWith('de') ? 'de' : 'en';

export const language = () => lang;
export function setLanguage(next) {
  lang = STRINGS[next] ? next : 'en';
  try { localStorage.setItem('ldraw-stl.lang', lang); } catch { /* storage blocked */ }
  document.documentElement.lang = lang;
}
export function t(key, vars = {}) {
  const s = STRINGS[lang][key] ?? STRINGS.en[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? `{${k}}`));
}
export const number = (x, digits = 1) => x.toLocaleString(lang, { minimumFractionDigits: digits, maximumFractionDigits: digits });
